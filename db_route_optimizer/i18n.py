_lang = "en"


def set_lang(lang: str | None) -> str:
    """Set active language. Accepts 'en' (default) or 'pt-BR'."""
    global _lang
    if not lang or lang.lower() in ("en", "en-us", "english"):
        _lang = "en"
    elif lang.lower() in ("pt-br", "pt_br", "pt", "portuguese"):
        _lang = "pt-BR"
    else:
        _lang = "en"
    return _lang


def get_lang() -> str:
    return _lang


def t(key: str, **kwargs: Any) -> str:
    """Translate `key` with optional format kwargs."""
    table = _STRINGS.get(_lang) or _STRINGS["en"]
    template = table.get(key) or _STRINGS["en"].get(key) or key
    if kwargs:
        return template.format(**kwargs)
    return template


def add_lang_arg(parser) -> None:
    """Attach --lang to an argparse parser."""
    parser.add_argument(
        "--lang",
        default="en",
        help="output language: en (default) or pt-BR",
    )
